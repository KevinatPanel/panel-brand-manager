create policy "authenticated full access" on public.ad_library_checks
  for all to authenticated using (true) with check (true);
create policy "authenticated full access" on public.client_programs
  for all to authenticated using (true) with check (true);
create policy "authenticated full access" on public.playbook_entries
  for all to authenticated using (true) with check (true);
